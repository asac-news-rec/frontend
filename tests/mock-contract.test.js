import {test} from 'node:test';
import assert from 'node:assert/strict';
import '../src/contract-mock-api.js';
const create = () => globalThis.NewsContractMock.createMockApi();
test('모의 피드는 계약 기사 필드·cursor·조회별 새 ID를 반환한다', async () => {
 const api=create(), first=await api.getFeed({reader_id:'test-user',cursor:null});
 assert.equal(first.items.length,3); assert.ok(first.next_cursor);
 assert.deepEqual(first.items[0].paragraphs,['화면 검증용 첫 번째 문단입니다.','실제 보도가 아닌 가상 본문입니다.']);
 assert.equal(first.items[0].image_url,null);assert.equal(first.items[0].is_synthetic,true);
 const second=await api.getFeed({reader_id:'test-user',cursor:first.next_cursor});
 assert.equal(second.next_cursor,null);assert.deepEqual(second.items.map(item=>item.position),[4,5,6]);
 assert.equal(new Set([...first.items,...second.items].map(a=>a.article_id)).size,6);
 const repeated=await api.getFeed({reader_id:'test-user',cursor:first.next_cursor});assert.deepEqual(repeated.items.map(item=>item.position),[4,5,6]);
 const again=await api.getFeed({reader_id:'test-user',cursor:null});assert.equal(again.items[0].position,1);assert.notEqual(first.request_id,again.request_id);assert.notEqual(first.items[0].impression_id,again.items[0].impression_id);
 await assert.rejects(api.getFeed({reader_id:'other',cursor:first.next_cursor}),/INVALID_CURSOR/);
 await assert.rejects(api.getFeed({user_id:'test-user',cursor:null}),/INVALID_FEED_REQUEST/);
});
test('모의 행동은 새 envelope·종류를 검증하고 중복과 충돌을 구분한다', async () => {
 const api=create();const feed=await api.getFeed({reader_id:'test-user',cursor:null});
 const event={event_id:crypto.randomUUID(),event_type:'article_open',event_time:'2026-11-02T00:00:00Z',impression_id:feed.items[0].impression_id,page_type:'list'};
 assert.equal((await api.send({events:[event]})).results[0].status,'accepted');
 assert.equal((await api.send({events:[event]})).results[0].status,'duplicate');assert.equal(api.storedCount,1);
 await assert.rejects(api.send({events:[{...event,event_type:'like'}]}),/CONFLICT/);
 await assert.rejects(api.send(event),/ENVELOPE/);
 await assert.rejects(api.send({events:[{...event,event_id:crypto.randomUUID(),event_type:'click',action:'article_open'}]}),/INVALID_EVENT/);
 const exposure={...event,event_id:crypto.randomUUID(),event_type:'exposure',duration_ms:3000,ended_at:'2026-11-02T00:00:03Z'};
 await api.send({events:[exposure]});assert.equal(api.storedCount,2);
 const close={...event,event_id:crypto.randomUUID(),event_type:'article_close',page_type:'detail'};
 assert.equal((await api.send({events:[close]})).results[0].status,'accepted');
 await assert.rejects(api.send({events:[{...close,event_id:crypto.randomUUID(),duration_ms:5000}]}),/INVALID_CLICK/);
 await assert.rejects(api.send({events:[{...exposure,event_id:crypto.randomUUID(),page_type:'detail'}]}),/INVALID_EXPOSURE/);
 api.setOffline(true);await assert.rejects(api.send({events:[event]}),/OFFLINE/);api.setOffline(false);
 assert.equal((await api.send({events:[event]})).results[0].status,'duplicate');
});
